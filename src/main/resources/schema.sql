CREATE SCHEMA IF NOT EXISTS app_auth;
SET search_path TO app_auth, public;

CREATE TABLE app_auth.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_activated BOOLEAN NOT NULL DEFAULT false,
    activation_token_hash VARCHAR(255),
    activation_expires_at TIMESTAMPTZ DEFAULT (now() + INTERVAL '24 hours'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app_auth.user_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_auth.users(id) ON DELETE CASCADE,
    event_type VARCHAR(64) NOT NULL,
    ip_address INET,
    user_agent TEXT,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION app_auth.cleanup_stale_unactivated_users()
RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM app_auth.users
    WHERE is_activated = FALSE
      AND created_at < NOW() - INTERVAL '48 hours';
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trg_cleanup_stale_users
AFTER INSERT ON app_auth.users
FOR EACH STATEMENT
EXECUTE FUNCTION app_auth.cleanup_stale_unactivated_users();