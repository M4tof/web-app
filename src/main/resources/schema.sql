-- ============================================================================
-- SCHEMA DEFINITION & SEARCH PATH
-- ============================================================================
CREATE SCHEMA IF NOT EXISTS app_auth;;
--DROP SCHEMA IF EXISTS app_auth CASCADE;;

SET
  search_path TO app_auth,
  public;;

-- ============================================================================
-- 1. USERS TABLE
-- Tracks identities, credentials, 2FA status, and lockout states.
-- ============================================================================
CREATE TABLE IF NOT EXISTS
  app_auth.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RFC 5321 (Errata 1690) restricts max email path to 254 octets
    email VARCHAR(254) NOT NULL UNIQUE,
    -- Standard serialized Argon2id string ($argon2id$v=19$m=...$salt$hash) is ~96-98 chars
    password_hash VARCHAR(100) NOT NULL,
    is_activated BOOLEAN NOT NULL DEFAULT FALSE,
    -- Exact SHA-256 hex digest: 256 bits = 32 bytes = exactly 64 hex characters
    activation_token_hash CHAR(64),
    -- Valid for 24h; set to NULL upon activation
    activation_expires_at TIMESTAMPTZ DEFAULT (NOW() + INTERVAL '24 hours'),
    -- Progressive Account Lockout (NFR-14)
    failed_login_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ, -- NULL if account is not locked
    -- Multi-Factor Authentication / TOTP (NFR-15)
    -- RFC 6238 standard 160-bit (20-byte) secret encoded in Base32 is exactly 32 chars
    totp_secret VARCHAR(32),
    is_2fa_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    -- Password Reset Lifecycle (NFR-16)
    -- Exact SHA-256 hex digest of the 32-byte CSPRNG reset token; set to NULL upon use
    reset_token_hash CHAR(64),
    reset_expires_at TIMESTAMPTZ, -- Short-lived (15 minutes)
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );;

-- ============================================================================
-- 2. USER SESSIONS TABLE
-- Stateful server-side session management with idle & absolute timeouts.
-- ============================================================================
CREATE TABLE IF NOT EXISTS
  app_auth.user_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_auth.users (id) ON DELETE CASCADE,
    -- Exact SHA-256 hex digest of the 32-byte CSPRNG token delivered via HttpOnly cookie
    session_token_hash CHAR(64) NOT NULL UNIQUE,
    -- POSIX INET6_ADDRSTRLEN / RFC 4291 maximum length for IPv4-mapped IPv6 is 45 chars
    ip_address VARCHAR(45),
    -- User-Agent headers have no RFC length cap; stored as TEXT to prevent truncation
    user_agent TEXT,
    -- Timestamp updated on every authenticated request for idle timeout (e.g. 15m)
    last_accessed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Timestamp preserved from initial login for absolute timeout (e.g. 12h)
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );;

-- ============================================================================
-- 3. 2FA RECOVERY CODES TABLE
-- Single-use emergency backup codes for two-factor authentication.
-- ============================================================================
CREATE TABLE IF NOT EXISTS
  app_auth.user_recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_auth.users (id) ON DELETE CASCADE,
    -- Exact SHA-256 hex digest of the backup code (raw codes are never stored plain)
    code_hash CHAR(64) NOT NULL,
    -- NULL until consumed; populated with timestamp upon use to enforce single-use
    used_at TIMESTAMPTZ
  );;

-- ============================================================================
-- 4. USER LOGS TABLE
-- Security audit trail with debounced failure roll-up counters.
-- ============================================================================
CREATE TABLE IF NOT EXISTS
  app_auth.user_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nullable to allow logging unauthenticated attacks or duplicate registrations
    user_id BIGINT REFERENCES app_auth.users (id) ON DELETE CASCADE,
    -- Controlled internal lifecycle event names (< 32 chars)
    event_type VARCHAR(32) NOT NULL,
    -- POSIX INET6_ADDRSTRLEN max IP length (45 chars)
    ip_address VARCHAR(45),
    user_agent TEXT,
    -- Debounced attempt counter (prevents table bloating during brute-force/DoS attacks)
    failed_attempts BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );;

-- ============================================================================
-- 5. AUTOMATED DATA HYGIENE (TRIGGER)
-- Purges unactivated accounts older than 48 hours on new registration inserts.
-- ============================================================================
CREATE
OR REPLACE FUNCTION app_auth.cleanup_stale_unactivated_users () RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM app_auth.users
    WHERE is_activated = FALSE
      AND created_at < NOW() - INTERVAL '48 hours';
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;;

CREATE
OR REPLACE TRIGGER trg_cleanup_stale_users
AFTER INSERT ON app_auth.users FOR EACH STATEMENT
EXECUTE FUNCTION app_auth.cleanup_stale_unactivated_users ();;